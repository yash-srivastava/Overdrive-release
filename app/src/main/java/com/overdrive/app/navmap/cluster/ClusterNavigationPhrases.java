    private static final Pattern[] PATTERNS = new Pattern[PHRASES.length];
    static {
        for (int i = 0; i < PHRASES.length; i++) PATTERNS[i] = Pattern.compile(
                "(?<![\\p{L}\\p{N}_])" + Pattern.quote((String) PHRASES[i][0])
                + "(?![\\p{L}\\p{N}_])");
    }
    private ClusterNavigationPhrases() {}

    static int canIcon(String text) {
        for (int i = 0; i < PHRASES.length; i++) {
            Matcher match = PATTERNS[i].matcher(text);
            while (match.find()) {
                String prefix = text.substring(0, match.start());
                // A directional word in the named road after onto/on/sur is data, not an instruction.
                if (prefix.matches("(?s).*\\b(?:onto|on|sur|vers|auf)\\s+[^,;]*")) continue;
                return (Integer) PHRASES[i][1];
            }
        }
        return -1;
    }

    static String instructionText(String text) {
        // Apply the same road-name exclusion before the generic parser fallback; otherwise a
        // rejected phrase in "on Roundabout Road" could reappear through a substring match.
        return ROAD_NAME.matcher(text).replaceAll("");
    }
